import { readFile, readdir, mkdir, writeFile, stat } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { createElement as h } from "react";
import { ImageResponse } from "next/og.js";

const root = fileURLToPath(new URL("../", import.meta.url));
for (const name of ["koii", "kasmate"]) {
  for (const version of [2, 3]) {
    const file = `public/media/${name}-demo-v${version}.mp4`;
    const { size } = await stat(path.join(root, file));
    if (size === 0 || size > 2 * 1024 * 1024) {
      throw new Error(`${file} must be between 1 byte and 2 MB for the demo range handler.`);
    }
  }
}
const directory = path.join(root, "content/projects");
const sources = {};
for (const file of (await readdir(directory)).filter((file) => file.endsWith(".md")).sort()) {
  const source = await readFile(path.join(directory, file), "utf8");
  if (!/^---\r?\n[\s\S]*?\r?\n---\r?\n/.test(source)) {
    throw new Error(`Missing frontmatter: ${file}`);
  }
  sources[file.slice(0, -3)] = source;
}
if (!Object.keys(sources).length) throw new Error("No project content found.");
await mkdir(path.join(root, "lib/generated"), { recursive: true });
await writeFile(path.join(root, "lib/generated/project-sources.ts"),
  `// Generated by scripts/prepare-content.mjs; edit content/projects instead.\nexport const projectSources: Record<string, string> = ${JSON.stringify(sources, null, 2)};\n`);

const font = await readFile(path.join(root, "node_modules/@fontsource/ibm-plex-sans/files/ibm-plex-sans-latin-500-normal.woff"));
const image = new ImageResponse(
  h("div", { style: { width: "100%", height: "100%", display: "flex", background: "#faf8f4", color: "#252b29", padding: 72, flexDirection: "column", justifyContent: "space-between", fontFamily: "Plex" } },
    h("div", { style: { display: "flex", justifyContent: "space-between", fontSize: 25 } },
      h("span", null, "Ari Hendrawan"), h("span", { style: { color: "#62675f" } }, "Risk & Data Scientist")),
    h("div", { style: { display: "flex", flexDirection: "column", fontSize: 76, lineHeight: 1.12, letterSpacing: -3 } },
      h("span", null, "Hi, I’m Ari."), h("span", null, "I work on"), h("span", { style: { color: "#ac432d" } }, "credit risk.")),
    h("div", { style: { display: "flex", fontSize: 22, color: "#62675f" } }, "Credit scoring, decision rules, and personal apps. · arih.ai.id")),
  { width: 1200, height: 630, fonts: [{ name: "Plex", data: font, style: "normal", weight: 500 }] },
);
await writeFile(path.join(root, "app/opengraph-image.png"), Buffer.from(await image.arrayBuffer()));
console.log(`Prepared ${Object.keys(sources).length} projects and Open Graph image.`);
